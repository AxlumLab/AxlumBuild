    std::string ninjaPath(const fs::path& p)
    {
        return NinjaSyntax::escapeNinjaPath(p.generic_string());
    }

    std::string quoteJson(const std::string& s)
    {
        std::string escaped = "\"";
        constexpr char hex[] = "0123456789abcdef";
        for (unsigned char c : s)
        {
            switch (c)
            {
            case '\\':
                escaped += "\\\\";
                break;
            case '"':
                escaped += "\\\"";
                break;
            case '\n':
                escaped += "\\n";
                break;
            case '\r':
                escaped += "\\r";
                break;
            case '\t':
                escaped += "\\t";
                break;
            default:
                if (c < 0x20)
                {
                    escaped += "\\u00";
                    escaped += hex[c >> 4];
                    escaped += hex[c & 15];
                }
                else
                    escaped += static_cast<char>(c);
            }
        }
        return escaped + '"';
    }

    std::string ninjaCommand(const std::vector<std::string>& args)
    {
        std::string command;
        for (const auto& arg : args)
        {
            if (!command.empty())
                command += ' ';
            command += Process::quoteShellArg(arg);
        }
        return NinjaSyntax::escapeNinjaValue(command);
    }

    void NinjaBackend::generateNinja(const BuildGraph& graph, const fs::path& buildDir, const fs::path& executable)
    {
        const auto environmentFile = fs::absolute(buildDir / "axlum.environment.json");
        FileSystem::writeEnvironment(environmentFile, graph.m_environment);
        std::ostringstream ninja;
        ninja << "# Generated by AxlumBuild. Edits will be overwritten.\n"
              << "ninja_required_version = 1.10\n\n";
        ninja << "rule axlum_reconfigure\n  command = " << ninjaCommand({executable.string(), "__refresh", "-B", fs::absolute(buildDir).string()})
              << "\n  description = Checking AxlumBuild configuration\n  generator = 1\n  restat = 1\n"
              << "build axlum-configure-always: phony\n"
              << "build build.ninja: axlum_reconfigure | axlum-configure-always\n\n";
        bool hasAlways = false;
        for (const auto& action : graph.m_actions)
            hasAlways |= action.m_always;
        if (hasAlways)
            ninja << "build axlum-always-dirty: phony\n\n";
        for (std::size_t i = 0; i < graph.m_actions.size(); ++i)
        {
            const auto& a = graph.m_actions[i];
            if (a.m_outputs.empty())
                throw std::runtime_error("cannot generate empty-output action");
            for (const auto& o : a.m_outputs)
                fs::create_directories(o.parent_path());
            if (!a.m_depfile.empty())
                fs::create_directories(a.m_depfile.parent_path());
            std::string rule = "axlum_rule_" + std::to_string(i);
            std::vector<std::string> invoke = {executable.string(), "__run", "--cwd", a.m_workingDirectory.string()};
            invoke.insert(invoke.end(), {"--env-file", environmentFile.string()});
            for (const auto& out : a.m_outputs)
            {
                invoke.push_back("--out");
                invoke.push_back(out.string());
            }
            if (a.m_depsStyle == "msvc-json")
            {
                invoke.insert(invoke.end(), {"--msvc-json", a.m_outputs[0].string() + ".json", "--depfile", a.m_depfile.string()});
            }
            invoke.push_back("--");
            if (a.m_rsp)
            {
                const fs::path response = fs::path(a.m_outputs[0].string() + ".rsp");
                invoke.push_back(a.m_argv.at(0));
                invoke.push_back("@" + response.string());
                std::string content;
                for (std::size_t j = 1; j < a.m_argv.size(); ++j)
                {
                    if (!content.empty())
                        content += ' ';
                    content += Process::quoteRspArg(a.m_argv[j], a.m_gnuRsp);
                }
                ninja << "rule " << rule << "\n"
                      << "  command = " << ninjaCommand(invoke) << "\n"
                      << "  description = " << NinjaSyntax::escapeNinjaValue(a.m_name) << "\n"
                      << "  rspfile = " << ninjaPath(response) << "\n"
                      << "  rspfile_content = " << NinjaSyntax::escapeNinjaValue(content) << "\n";
            }
            else
            {
                invoke.insert(invoke.end(), a.m_argv.begin(), a.m_argv.end());
                ninja << "rule " << rule << "\n"
                      << "  command = " << ninjaCommand(invoke) << "\n"
                      << "  description = " << NinjaSyntax::escapeNinjaValue(a.m_name) << "\n";
            }
            if (!a.m_depfile.empty())
                ninja << "  depfile = " << ninjaPath(a.m_depfile) << "\n";
            if (!a.m_depsStyle.empty())
                ninja << "  deps = " << (a.m_depsStyle == "msvc-json" ? "gcc" : a.m_depsStyle) << "\n";
            if (a.m_depsStyle == "msvc")
                ninja << "  msvc_deps_prefix = Note: including file:\n";
            if (a.m_restat)
                ninja << "  restat = 1\n";
            ninja << "build";
            for (const auto& out : a.m_outputs)
                ninja << ' ' << ninjaPath(out);
            ninja << ": " << rule;
            for (const auto& in : a.m_inputs)
                ninja << ' ' << ninjaPath(in);
            ninja << " | " << ninjaPath(environmentFile);
            if (a.m_always)
                ninja << " axlum-always-dirty";
            if (!a.m_orderOnly.empty())
            {
                ninja << " ||";
                for (const auto& dep : a.m_orderOnly)
                    ninja << ' ' << ninjaPath(dep);
            }
            ninja << "\n\n";
        }
        for (const auto& [name, outputs] : graph.m_targetOutputs)
        {
            if (name == "all" || name == "axlum-always-dirty" || name == "axlum-configure-always" || name == "build.ninja")
                throw std::runtime_error("target.name '" + name + "' reserved by Ninja generator");
            ninja << "build " << NinjaSyntax::escapeNinjaPath(name) << ": phony";
            for (const auto& out : outputs)
                ninja << ' ' << ninjaPath(out);
            ninja << "\n";
        }
        for (const auto& [alias, target] : graph.m_targetAliases)
            ninja << "build " << NinjaSyntax::escapeNinjaPath(alias) << ": phony " << NinjaSyntax::escapeNinjaPath(target) << '\n';
        std::size_t unavailableIndex = 0;
        for (const auto& [name, reason] : graph.m_disabledTargets)
        {
            if ((name == "all" || name == "axlum-always-dirty" || name == "axlum-configure-always" || name == "build.ninja") ||
                graph.m_targetOutputs.contains(name) || graph.m_targetAliases.contains(name))
                throw std::runtime_error("unavailable target name collision: " + name);
            const auto rule = "axlum_unavailable_" + std::to_string(unavailableIndex++);
            const auto sentinel = buildDir / ".axlum-unavailable" / (FileSystem::shortHash(name) + ".stamp");
            ninja << "rule " << rule << "\n  command = " << ninjaCommand({executable.string(), "__unsupported-target", reason}) << "\n";
            ninja << "build " << ninjaPath(sentinel) << ": " << rule << "\nbuild " << NinjaSyntax::escapeNinjaPath(name) << ": phony " << ninjaPath(sentinel)
                  << "\n";
        }
        ninja << "build all: phony";
        for (const auto& [name, _] : graph.m_targetOutputs)
            ninja << ' ' << NinjaSyntax::escapeNinjaPath(name);
        ninja << "\ndefault all\n";
        FileSystem::writeIfChanged(buildDir / "build.ninja", ninja.str());
        FileSystem::writeIfChanged(
            buildDir / "axlum.target-selection.json", nlohmann::json{{"aliases", graph.m_targetAliases}, {"disabled", graph.m_disabledTargets}}.dump(2) + "\n"
        );
    }

    void NinjaBackend::generateCompileCommands(const BuildGraph& graph, const fs::path& buildDir)
    {
        std::ostringstream json;
        json << "[\n";
        bool first = true;
        for (const auto& action : graph.m_actions)
        {
            if (!action.m_compile)
                continue;
            if (!first)
                json << ",\n";
            first = false;
            json << "  {\"directory\": " << quoteJson(action.m_workingDirectory.string()) << ", \"file\": " << quoteJson(action.m_source.string())
                 << ", \"output\": " << quoteJson(action.m_outputs.at(0).string()) << ", \"arguments\": [";
            for (std::size_t i = 0; i < action.m_argv.size(); ++i)
            {
                if (i)
                    json << ", ";
                json << quoteJson(action.m_argv[i]);
            }
            json << "], \"command\": "
                 << quoteJson(
                        [&]
                        {
                            std::string cmd;
                            for (const auto& arg : action.m_argv)
                            {
                                if (!cmd.empty())
                                    cmd += ' ';
                                cmd += Process::quoteShellArg(arg);
                            }
                            return cmd;
                        }()
                    )
                 << "}";
        }
        json << "\n]\n";
        FileSystem::writeIfChanged(buildDir / "compile_commands.json", json.str());
    }
