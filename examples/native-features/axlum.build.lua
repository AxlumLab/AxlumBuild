workspace("NativeFeatures")
    configuration("Debug", "Release")
    architecture("x64")
    cppdialect("C++20")
    includedirs("include")
    warnings("Extra")
    warningsaserrors(true)
    symbols("On")
    runtime("Dynamic")
    exceptions("On")
    rtti(true)
    pchheader("include/Pch.hpp")
    filter("configurations:Debug")
        optimize("Off")
        lto(false)
    filter("configurations:Release")
        optimize("Speed")
        lto(true)
    filter({})

target("FeatureRuntime")
    kind("SharedLibrary")
    files({"src/Library.cpp", "src/Pch.cpp"})
    defines("FEATURE_EXPORTS=1")
    public_includedirs("include")
    pchsource("src/Pch.cpp")
    targetname("feature_runtime")
    targetdir("products/${config}/runtime")
    implibdir("products/${config}/import")
    objdir("objects/${config}/${target}")
    runtimefiles("data/config.txt")
    optionalruntimefiles("data/optional.txt")
    when("windows", function()
        moduledefinition("src/exports.def")
    end)

target("FeatureApp")
    kind("ConsoleApp")
    files({"src/Main.cpp", "src/Helper.c"})
    private_deps("FeatureRuntime")
    targetname("feature_app")
    targetdir("products/${config}/app")
    objdir("objects/${config}/${target}")
    when("windows", function()
        resources("src/app.rc")
        resourceinputs({"include/Version.h", "data/payload.bin"})
        win32manifest("src/app.manifest")
        delayloaddlls("feature_runtime.dll")
        subsystem("Console")
        filter("configurations:Debug")
            incrementallink(true)
        filter({})
    end)
