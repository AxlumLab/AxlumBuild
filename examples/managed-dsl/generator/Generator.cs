using System;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

[Generator]
public sealed class ValueGenerator : ISourceGenerator
{
    public void Initialize(GeneratorInitializationContext context) {}

    public void Execute(GeneratorExecutionContext context)
    {
        var text = context.AdditionalFiles.Length == 0 ? "42" : context.AdditionalFiles[0].GetText(context.CancellationToken)?.ToString().Trim();
        if (text == "warn")
            context.ReportDiagnostic(Diagnostic.Create(
                new DiagnosticDescriptor("AXL001", "Input", "Generator input requests a warning", "Build", DiagnosticSeverity.Warning, true), Location.None
            ));
        var value = int.TryParse(text, out var number) ? number : 42;
        context.AddSource(
            "GeneratedValue.g.cs",
            SourceText.From(
                "// <auto-generated/>\nnamespace ManagedSample { public static class " + "Generated { public const int s_value = " + value + "; } }",
                Encoding.UTF8
            )
        );
    }
}
